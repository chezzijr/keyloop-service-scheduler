"""Initial schema: reference tables, appointment and its guards.

Hand-written to match docs/details/data-model.md and the Data Model section of
docs/design.md. The exclusion constraints are created in the order no_vehicle_overlap,
no_tech_overlap, no_bay_overlap, so a resent request fails on the vehicle first.

Revision ID: 0001
Revises:
Create Date: 2026-11-02
"""

from collections.abc import Sequence

from alembic import op

revision: str = "0001"
down_revision: str | None = None
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

UPGRADE = """
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE dealership (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    timezone text NOT NULL
);

CREATE TABLE bay_type (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE
);

CREATE TABLE service_bay (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dealership_id bigint NOT NULL REFERENCES dealership (id),
    bay_type_id bigint NOT NULL REFERENCES bay_type (id),
    name text NOT NULL,
    UNIQUE (id, dealership_id)
);

CREATE TABLE skill (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE
);

CREATE TABLE technician (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dealership_id bigint NOT NULL REFERENCES dealership (id),
    name text NOT NULL,
    UNIQUE (id, dealership_id)
);

CREATE TABLE technician_skill (
    technician_id bigint NOT NULL REFERENCES technician (id),
    skill_id bigint NOT NULL REFERENCES skill (id),
    PRIMARY KEY (technician_id, skill_id)
);

CREATE TABLE service_type (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL,
    duration_minutes integer NOT NULL,
    buffer_minutes integer NOT NULL DEFAULT 15,
    required_skill_id bigint NOT NULL REFERENCES skill (id),
    required_bay_type_id bigint NOT NULL REFERENCES bay_type (id),
    CONSTRAINT duration_valid CHECK (duration_minutes > 0 AND duration_minutes % 15 = 0),
    CONSTRAINT buffer_valid CHECK (buffer_minutes >= 0 AND buffer_minutes % 15 = 0)
);

CREATE TABLE customer (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    email text NOT NULL
);

CREATE TABLE vehicle (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customer (id),
    vin text NOT NULL UNIQUE,
    make text NOT NULL,
    model text NOT NULL
);

CREATE TABLE opening_hours (
    dealership_id bigint NOT NULL REFERENCES dealership (id),
    weekday smallint NOT NULL,
    opens_at time NOT NULL,
    closes_at time NOT NULL,
    PRIMARY KEY (dealership_id, weekday),
    CONSTRAINT weekday_valid CHECK (weekday BETWEEN 1 AND 7),
    CONSTRAINT hours_valid CHECK (opens_at < closes_at)
);

CREATE TABLE appointment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customer (id),
    vehicle_id bigint NOT NULL REFERENCES vehicle (id),
    dealership_id bigint NOT NULL REFERENCES dealership (id),
    service_type_id bigint NOT NULL REFERENCES service_type (id),
    service_bay_id bigint NOT NULL,
    technician_id bigint NOT NULL,
    during tstzrange NOT NULL,
    ends_at timestamptz NOT NULL,
    status text NOT NULL DEFAULT 'confirmed',
    created_at timestamptz NOT NULL DEFAULT now(),
    cancelled_at timestamptz
);

-- the overlap rules depend on status, so a typo like 'canceled' must be impossible
ALTER TABLE appointment
  ADD CONSTRAINT status_valid CHECK (status IN ('confirmed', 'cancelled'));

-- the bay and technician must belong to the appointment's dealership
ALTER TABLE appointment
  ADD CONSTRAINT bay_in_dealership
  FOREIGN KEY (service_bay_id, dealership_id) REFERENCES service_bay (id, dealership_id);

ALTER TABLE appointment
  ADD CONSTRAINT tech_in_dealership
  FOREIGN KEY (technician_id, dealership_id) REFERENCES technician (id, dealership_id);

-- the work end lies inside the reserved range (the buffer may be 0)
ALTER TABLE appointment
  ADD CONSTRAINT ends_at_in_during
  CHECK (lower(during) < ends_at AND ends_at <= upper(during));

-- The three rules against double-booking. Read each one as:
--   "reject a new row if an active row has the same vehicle / technician / bay
--    (WITH =) and a time range that overlaps (WITH &&)"
-- during = [start, end of the cleanup buffer): it includes the start and excludes the
-- end, so a booking that ends at 11:15 and one that starts at 11:15 do not overlap.
-- gist is the index type that answers "do these ranges overlap?" quickly (btree_gist
-- lets it compare plain ids too). Cancelled rows are ignored, so a cancel frees the slot
-- at once. Postgres runs these checks on every insert, also against rows that other
-- transactions have not committed yet, so two API servers can never both win a slot.

-- a vehicle cannot be in two bookings at once. This also stops a resent request.
-- Created first, so Postgres checks it first.
ALTER TABLE appointment
  ADD CONSTRAINT no_vehicle_overlap
  EXCLUDE USING gist (vehicle_id WITH =, during WITH &&)
  WHERE (status <> 'cancelled');

-- a technician cannot work on two bookings at once
ALTER TABLE appointment
  ADD CONSTRAINT no_tech_overlap
  EXCLUDE USING gist (technician_id WITH =, during WITH &&)
  WHERE (status <> 'cancelled');

-- a bay cannot hold two bookings at once
ALTER TABLE appointment
  ADD CONSTRAINT no_bay_overlap
  EXCLUDE USING gist (service_bay_id WITH =, during WITH &&)
  WHERE (status <> 'cancelled');
"""

DOWNGRADE = """
DROP TABLE appointment, opening_hours, vehicle, customer, service_type, technician_skill,
    technician, skill, service_bay, bay_type, dealership;
DROP EXTENSION IF EXISTS btree_gist;
"""


def run(sql: str) -> None:
    # asyncpg prepares each statement and refuses several commands in one, so run them one by one
    for statement in sql.split(";\n"):
        if statement.strip():
            op.execute(statement)


def upgrade() -> None:
    run(UPGRADE)


def downgrade() -> None:
    run(DOWNGRADE)
